type ScenarioDifficulty =
  "BEGINNER" | "INTERMEDIATE" | "UPPER_INTERMEDIATE" | "ADVANCED";

const DEFAULT_HAN_VOICE = "cedar";

/**
 * Redesigned 2026-08-10 (user request): one word at a time instead of a
 * full grid up front — a flashcard, its example(s), and a quick check
 * before moving to the next word. Every check is built from the lesson's
 * own vocabulary and example sentences (`vocabulary-quiz.ts`), never
 * generated by AI, so it costs nothing per learner per word. Examples are
 * hand-authored content (live AI generation removed 2026-08-14) and arrive
 * already loaded with `vocabulary` (`content/vocabulary.ts`'s
 * `getVocabularyForLesson`), same as Grammar's - no per-word fetch or
 * loading spinner (2026-08-19, project/learning-journey-optimization.md
 * Facet C). Word arrival still fires one lightweight call
 * (`recordVocabularyWordSeenAction`) to mark the word as seen for progress
 * tracking, without re-fetching its content.
 *
 * Rhythm variation + quick test (2026-08-31, "no deberia ser mejor tener
 * ritmo variado" - marketing/retention conversation comparing HanGo to
 * Duolingo). The walkthrough used to ask every word the exact same fixed
 * sequence, every lesson, every time - 24-36 questions per lesson just in
 * this step. Two changes:
 *
 * 1. Which questions a word gets, how many, and in what order is now
 *    decided by `planVocabularyQuestions` (vocabulary-quiz.ts) - the same
 *    function `reflection.ts`'s scoring calls, seeded only off
 *    (lessonId, vocabularyItemId, difficulty, exampleCount), so client and
 *    server always agree on what was legitimately asked without either
 *    side trusting the other's report of it.
 * 2. A learner can opt into a "quick test" - one meaning-only question per
 *    word, all up front - instead of the full walkthrough. Scoring
 *    80%+ skips straight to `onContinue()` with the real (not inflated)
 *    score; scoring below that drops into the normal walkthrough, but only
 *    for the words answered wrong, not all of them. Quick-test attempts use
 *    their own `:quicktest` questionKey suffix (never `:meaning`), so they
 *    can never collide with or double-count against a walkthrough attempt.
 */
const QUICK_TEST_PASS_THRESHOLD = VOCABULARY_QUICK_TEST_PASS_THRESHOLD;

type VocabularyMode = "choose" | "quick-test" | "walkthrough";

export function VocabularyStep({
  vocabulary,
  difficulty,
  lessonId,
  onContinue,
}: {
  vocabulary: LessonWithContent["vocabulary"];
  difficulty: ScenarioDifficulty;
  lessonId: string;
  onContinue: () => void;
}) {
  const messages = useLessonMessages();
  const { showPinyin, showTranslation } = useLessonDisplayPrefs();
  const [mode, setMode] = useState<VocabularyMode>("choose");
  const [activeVocabulary, setActiveVocabulary] = useState(vocabulary);
  const [index, setIndex] = useState(0);
  /**
   * Position within the CURRENT word's own question plan (2026-09-26
   * restructure, "cuando aprendes el vocabulario paso a paso debes bajar
   * mucho"). `-1` is the word's flashcard + examples; `0..plan.length-1` is
   * one question screen at a time - previously every plan entry rendered
   * stacked in the same scrolling card, so a word with its full four-
   * question plan (meaning, chineseForm, blank, order) was one long card a
   * learner had to scroll through question by question anyway, just
   * without ever losing sight of the ones already answered. This makes
   * that same walk a sequence of screens instead, the same shape Grammar's
   * per-exercise cards and Comprehension already use.
   *
   * Answers remain batched on word boundaries, not sent per question.
   * Leaving the step now waits for the batch acknowledgement; failed
   * batches are retained for explicit retry before the Speaking snapshot.
   */
  const [screenIndex, setScreenIndex] = useState(-1);
  const [direction, setDirection] = useState<"forward" | "back">("forward");
  const [answeredByQuestion, setAnsweredByQuestion] = useState<
    Record<string, string>
  >({});
  const [quickTestIndex, setQuickTestIndex] = useState(0);
  const [quickTestAnswers, setQuickTestAnswers] = useState<
    Record<string, { optionId: string; isCorrect: boolean }>
  >({});
  const seenWordIdsRef = useRef<Set<string>>(new Set());
  /**
   * Buffers the current word's quiz answers instead of sending each one
   * the instant it's tapped - flushed as one batched call whenever the
   * learner leaves the word (Next/Back/finishing the step), not per
   * question (2026-08-19, project/learning-journey-optimization.md
   * Facet C follow-up). The green/red reveal itself is unaffected - it's
   * computed client-side (vocabulary-quiz.ts) and shown from local state
   * regardless of when/whether this buffer has been sent yet.
   */
  const [answerQueue] = useState(
    () =>
      new BufferedLessonAnswers<VocabularyQuizAttemptInput>((attempts) =>
        recordVocabularyQuizAttemptsAction(lessonId, attempts),
      ),
  );
  const [savingAnswers, setSavingAnswers] = useState(false);
  const [answerSaveError, setAnswerSaveError] = useState(false);
  const quickTestQueued = useRef(false);
  const finishing = useRef(false);
  const flushPendingAttempts = useCallback(
    () => answerQueue.flush(),
    [answerQueue],
  );
  useLessonLeaveGuard(flushPendingAttempts);

  function flushInBackground() {
    void flushPendingAttempts().catch(() => setAnswerSaveError(true));
  }

  async function finishAfterSaving(next: () => void) {
    if (finishing.current) return;
    finishing.current = true;
    setSavingAnswers(true);
    setAnswerSaveError(false);
    try {
      await flushPendingAttempts();
      next();
    } catch {
      setAnswerSaveError(true);
    } finally {
      finishing.current = false;
      setSavingAnswers(false);
    }
  }

  const current = activeVocabulary[index];
  const currentItem = current?.vocabularyItem;
  const isLast = index === activeVocabulary.length - 1;
  const currentExamples = currentItem?.examples ?? [];

  useEffect(() => {
    if (!currentItem) return;
    if (seenWordIdsRef.current.has(currentItem.id)) return;
    seenWordIdsRef.current.add(currentItem.id);
    void recordVocabularyWordSeenAction(currentItem.id);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [currentItem?.id]);

  // Safety net for SPA-internal navigation away from this step
  // (StepNavigation, browser back within the app) - a hard tab close/
  // refresh doesn't run this, same accepted trade-off as leaving mid-word
  // (see the chat record - at most one word's worth of attempts, never the
  // whole session).
  useEffect(() => {
    return () => {
      void flushPendingAttempts().catch(() => undefined);
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  // Memoized: a stable reference is required so the option-shuffling
  // useMemo calls downstream (VocabularyQuizCheck/VocabularyFillBlankCheck)
  // actually skip recompute on re-render instead of seeing a "new" array
  // every time and reshuffling anyway. Deliberately built from the *full*
  // `vocabulary` list, not `activeVocabulary` - distractor variety for any
  // question shouldn't shrink just because the walkthrough is only
  // covering a quick-test-remediation subset of words.
  const quizItems: VocabularyQuizItem[] = useMemo(
    () =>
      vocabulary.map((v) => ({
        id: v.vocabularyItem.id,
        meaning: v.vocabularyItem.meaning,
        pinyin: v.vocabularyItem.pinyin,
        chineseForm: v.vocabularyItem.chineseForm,
      })),
    [vocabulary],
  );

  const plan = useMemo(
    () =>
      currentItem
        ? planVocabularyQuestions(
            currentItem.id,
            lessonId,
            difficulty,
            currentExamples.length,
          )
        : [],
    [currentItem, lessonId, difficulty, currentExamples.length],
  );

  if (vocabulary.length === 0) {
    return (
      <div
        data-activity-surface="HAN_VOCABULARY"
        className="flex flex-col gap-4"
      >
        <SectionTitle>{messages.vocabulary.title}</SectionTitle>
        <Body>{messages.vocabulary.empty}</Body>
        <Button type="button" onClick={onContinue} className="self-start">
          {messages.common.continue}
        </Button>
      </div>
    );
  }

  function goToWord(nextIndex: number, nextDirection: "forward" | "back") {
    flushInBackground();
    setDirection(nextDirection);
    setIndex(nextIndex);
    setScreenIndex(-1);
  }

  function handleAnswer(
    questionKey: string,
    answer: VocabularyQuizAnswerInput,
    isCorrect: boolean,
    vocabularyItemId: string,
  ) {
    if (answeredByQuestion[questionKey]) return;
    setAnsweredByQuestion((previous) => ({
      ...previous,
      [questionKey]: answer.type === "OPTION" ? answer.optionId : "submitted",
    }));
    answerQueue.enqueue([
      {
        vocabularyItemId,
        questionKey,
        answer,
      },
    ]);
  }

  function startWalkthrough(words: LessonWithContent["vocabulary"]) {
    setActiveVocabulary(words);
    setIndex(0);
    setScreenIndex(-1);
    setMode("walkthrough");
  }

  function finishQuickTest(
    finalAnswers: Record<string, { optionId: string; isCorrect: boolean }>,
  ) {
    const attempts: VocabularyQuizAttemptInput[] = vocabulary.flatMap((v) => {
      const answer = finalAnswers[v.vocabularyItem.id];
      return answer
        ? [
            {
              vocabularyItemId: v.vocabularyItem.id,
              questionKey: `${v.vocabularyItem.id}:quicktest`,
              answer: { type: "OPTION" as const, optionId: answer.optionId },
            },
          ]
        : [];
    });
    if (!quickTestQueued.current) {
      answerQueue.enqueue(attempts);
      quickTestQueued.current = true;
    }

    const passedCount = Object.values(finalAnswers).filter(
      (answer) => answer.isCorrect,
    ).length;
    const passed = passedCount / vocabulary.length >= QUICK_TEST_PASS_THRESHOLD;

    const missed = vocabulary.filter(
      (v) => !finalAnswers[v.vocabularyItem.id]?.isCorrect,
    );
    void finishAfterSaving(() =>
      passed ? onContinue() : startWalkthrough(missed),
    );
  }

  const cardStyle: CSSProperties = {
    animation: "card-slide-in var(--duration-slow) var(--ease-standard)",
    ["--card-slide-x" as string]: direction === "forward" ? "24px" : "-24px",
  };

  if (mode === "choose") {
    return (
      <div
        data-activity-surface="HAN_VOCABULARY"
        className="flex flex-col gap-4"
      >
        <SectionTitle>{messages.vocabulary.title}</SectionTitle>

        <div className="relative overflow-hidden rounded-panel bg-elevated px-5 py-5">
          <Body className="max-w-[70%] font-display text-[1.15rem] italic">
            &ldquo;{messages.vocabulary.introduction}&rdquo;
          </Body>
          <div className="mt-2">
            <HanSpeechButton
              text={messages.vocabulary.introduction}
              experience="SHARED_AUDIO"
              voice={DEFAULT_HAN_VOICE}
              labels={{
                listen: messages.vocabulary.listenToHan,
                pause: messages.vocabulary.pauseHan,
                unavailable: messages.vocabulary.voiceUnavailable,
              }}
              responseLanguage="English"
            />
          </div>
          <HanMascot
            pose="curious"
            size={132}
            className="pointer-events-none absolute -right-3 -bottom-3 drop-shadow-[0_12px_18px_rgba(0,0,0,0.25)]"
          />
        </div>

        <div className="rounded-card bg-surface p-4">
          <Body className="font-semibold">
            {formatMessage(messages.vocabulary.alreadyKnow, {
              count: vocabulary.length,
            })}
          </Body>
          <Caption className="mt-1 text-text-muted">
            {formatMessage(messages.vocabulary.quickTestDescription, {
              threshold: Math.round(QUICK_TEST_PASS_THRESHOLD * 100),
            })}
          </Caption>
          <div className="mt-3 flex flex-col gap-2 sm:flex-row">
            <Button type="button" onClick={() => setMode("quick-test")}>
              {messages.vocabulary.quickTest}
            </Button>
            <Button
              type="button"
              variant="secondary"
              onClick={() => startWalkthrough(vocabulary)}
            >
              {messages.vocabulary.normalWalkthrough}
            </Button>
          </div>
        </div>
      </div>
    );
  }

  if (mode === "quick-test") {
    const qtEntry = vocabulary[quickTestIndex];
    const qtItem = qtEntry?.vocabularyItem;
    if (!qtItem) return null;
    const isLastQt = quickTestIndex === vocabulary.length - 1;
    const qtAnswer = quickTestAnswers[qtItem.id];

    return (
      <div
        data-activity-surface="HAN_VOCABULARY"
        className="flex flex-col gap-4"
      >
        <SectionTitle>{messages.vocabulary.quickTest}</SectionTitle>
        <div
          className="flex items-center justify-center gap-1.5"
          role="progressbar"
          aria-valuenow={quickTestIndex + 1}
          aria-valuemin={1}
          aria-valuemax={vocabulary.length}
          aria-label={messages.vocabulary.quickTestProgress}
        >
          {vocabulary.map((v, i) => (
            <span
              key={v.vocabularyItem.id}
              className={cn(
                "h-1.5 w-6 rounded-full transition-colors duration-base ease-standard",
                i < quickTestIndex && "bg-secondary-500",
                i === quickTestIndex && "bg-accent-500",
                i > quickTestIndex && "bg-border",
              )}
            />
          ))}
        </div>

        <VocabularyQuizCheck
          key={qtItem.id}
          question={formatMessage(messages.vocabulary.whatDoesMean, {
            word: qtItem.chineseForm,
          })}
          items={quizItems}
          currentItemId={qtItem.id}
          field="meaning"
          selectedOptionId={qtAnswer?.optionId}
          onAnswer={(answer, isCorrect) => {
            if (answer.type !== "OPTION") return;
            setQuickTestAnswers((previous) => ({
              ...previous,
              [qtItem.id]: { optionId: answer.optionId, isCorrect },
            }));
          }}
        />

        <div className="mt-2 flex items-center justify-between gap-3">
          <Caption className="text-text-muted">
            {quickTestIndex + 1} {messages.common.of} {vocabulary.length}
          </Caption>
          <Button
            type="button"
            disabled={savingAnswers || !qtAnswer}
            loading={savingAnswers}
            onClick={() => {
              if (isLastQt) {
                finishQuickTest(quickTestAnswers);
              } else {
                setQuickTestIndex(quickTestIndex + 1);
              }
            }}
          >
            {isLastQt
              ? messages.vocabulary.finishQuickTest
              : messages.common.next}
          </Button>
        </div>
        {answerSaveError && (
          <Body role="alert" className="text-error-500">
            {messages.header.saveError}
          </Body>
        )}
      </div>
    );
  }

  if (!currentItem) return null;

  // The screen this word is currently showing: -1 is its flashcard, any
  // other value indexes straight into `plan`.
  const currentEntry = screenIndex >= 0 ? plan[screenIndex] : undefined;
  const isLastScreenOfWord = screenIndex === plan.length - 1;
  const canAdvance =
    screenIndex === -1 ||
    Boolean(currentEntry && answeredByQuestion[currentEntry.key]);

  function handleBack() {
    if (screenIndex > -1) {
      setDirection("back");
      setScreenIndex(screenIndex - 1);
      return;
    }
    if (index > 0) goToWord(index - 1, "back");
  }

  function handleNext() {
    if (!isLastScreenOfWord) {
      setDirection("forward");
      setScreenIndex(screenIndex + 1);
      return;
    }
    if (isLast) {
      void finishAfterSaving(onContinue);
      return;
    }
    goToWord(index + 1, "forward");
  }

  return (
    <div data-activity-surface="HAN_VOCABULARY" className="flex flex-col gap-4">
      <SectionTitle>{messages.vocabulary.title}</SectionTitle>

      <div
        className="flex items-center justify-center gap-1.5"
        role="progressbar"
        aria-valuenow={index + 1}
        aria-valuemin={1}
        aria-valuemax={activeVocabulary.length}
        aria-label={messages.vocabulary.wordProgress}
      >
        {activeVocabulary.map((v, i) => (
          <span
            key={v.vocabularyItem.id}
            className={cn(
              "h-1.5 w-6 rounded-full transition-colors duration-base ease-standard",
              i < index && "bg-secondary-500",
              i === index && "bg-accent-500",
              i > index && "bg-border",
            )}
          />
        ))}
      </div>

      {/* Keyed on the screen, not just the word, so the slide-in animation
          plays for every question change too, not only when the word
          itself changes - the same cue Grammar's per-exercise cards use. */}
      <div
        key={`${currentItem.id}:${screenIndex}`}
        style={cardStyle}
        className="flex flex-col gap-3"
      >
        {screenIndex === -1 ? (
          <>
            <div className="relative overflow-hidden rounded-panel bg-elevated px-6 py-7 text-center">
              <div className="absolute top-3 right-3">
                <AudioPlayButton
                  label={formatMessage(messages.audio.pronunciation, {
                    word: currentItem.chineseForm,
                  })}
                  size="md"
                  fetchUrl={() => getVocabularyItemAudioAction(currentItem.id)}
                />
              </div>

              <ChineseText className="text-5xl">
                {currentItem.chineseForm}
              </ChineseText>
              {showPinyin && (
                <Pinyin className="mt-1 font-mono text-[1.05rem] text-accent-300">
                  {currentItem.pinyin}
                </Pinyin>
              )}
              <Body className="mt-1 font-semibold">{currentItem.meaning}</Body>
              {currentItem.partOfSpeech && (
                <span className="mt-2 inline-block rounded-full bg-page px-3 py-0.5 font-interface text-caption text-text-secondary">
                  {currentItem.partOfSpeech}
                </span>
              )}
            </div>

            <div className="rounded-card bg-surface p-4">
              <Caption className="text-text-muted">
                {messages.vocabulary.example}
              </Caption>

              {currentExamples.length === 0 && (
                <Caption className="mt-2">
                  {messages.vocabulary.noExamples}
                </Caption>
              )}

              {currentExamples.map((example) => (
                <div
                  key={example.id}
                  className="mt-2 flex gap-2 border-t border-border pt-2 first:border-t-0 first:pt-0"
                >
                  <AudioPlayButton
                    label={formatMessage(messages.audio.example, {
                      text: example.chineseText,
                    })}
                    fetchUrl={() => getVocabularyExampleAudioAction(example.id)}
                  />
                  <div className="flex flex-col gap-0.5">
                    <ChineseText className="text-body">
                      {example.chineseText}
                    </ChineseText>
                    {showPinyin && <Pinyin>{example.pinyin}</Pinyin>}
                    {showTranslation && (
                      <Translation>{example.translation}</Translation>
                    )}
                  </div>
                </div>
              ))}

              <AskAiButton
                label={messages.ai.practiceVocabulary}
                contextPatch={{
                  selectedDialogueLine: {
                    chineseText: currentItem.chineseForm,
                    pinyin: currentItem.pinyin,
                    translation: currentItem.meaning,
                  },
                }}
              />
            </div>
          </>
        ) : (
          currentEntry && (
            <VocabularyQuestionCard
              entry={currentEntry}
              quizItems={quizItems}
              currentItem={currentItem}
              currentExamples={currentExamples}
              selectedOptionId={answeredByQuestion[currentEntry.key]}
              onAnswer={(answer, isCorrect) =>
                handleAnswer(
                  currentEntry.key,
                  answer,
                  isCorrect,
                  currentItem.id,
                )
              }
            />
          )
        )}
      </div>

      {/* Question-within-word progress, shown only once there's more than
          one to count - a lone question needs no counter of its own. */}
      {plan.length > 1 && (
        <Caption className="self-center text-text-muted">
          {formatMessage(messages.vocabulary.questionProgress, {
            current: screenIndex + 1,
            total: plan.length,
          })}
        </Caption>
      )}

      <div className="mt-2 flex items-center justify-between gap-3">
        <button
          type="button"
          onClick={handleBack}
          disabled={savingAnswers || (index === 0 && screenIndex === -1)}
          className="flex items-center gap-1 font-interface text-supporting text-text-secondary transition-opacity duration-fast ease-standard hover:text-text-primary disabled:pointer-events-none disabled:opacity-0"
        >
          <ChevronLeft className="size-4" aria-hidden="true" />
          {messages.common.back}
        </button>

        <Caption className="text-text-muted">
          {index + 1} {messages.common.of} {activeVocabulary.length}
        </Caption>

        <Button
          type="button"
          onClick={handleNext}
          disabled={!canAdvance || savingAnswers}
          loading={savingAnswers}
        >
          {isLast && isLastScreenOfWord
            ? messages.common.continue
            : isLastScreenOfWord
              ? messages.vocabulary.nextWord
              : messages.common.next}
        </Button>
      </div>
      {answerSaveError && (
        <Body role="alert" className="text-error-500">
          {messages.header.saveError}
        </Body>
      )}
    </div>
  );
}

/**
 * One question screen, as a real component rather than a helper function
 * called inline or a `.map()` over a synthetic array (2026-09-26). Both of
 * those shapes tripped React's ref-safety lint rule on `onAnswer`'s closure
 * over `handleAnswer` (which originally pushed into `VocabularyStep`'s
 * answer buffer) even though the buffer is only ever touched later,
 * inside a real click handler - the rule's static analysis apparently
 * trusts a genuine component boundary here in a way it didn't trust a
 * helper function or an inline array literal built fresh each render. The
 * branching itself is unchanged from the original stacked version, just
 * picking one entry instead of mapping every entry at once.
 */
function VocabularyQuestionCard({
  entry,
  quizItems,
  currentItem,
  currentExamples,
  selectedOptionId,
  onAnswer,
}: {
  entry: VocabularyQuestionPlan;
  quizItems: VocabularyQuizItem[];
  currentItem: LessonWithContent["vocabulary"][number]["vocabularyItem"];
  currentExamples: LessonWithContent["vocabulary"][number]["vocabularyItem"]["examples"];
  selectedOptionId: string | undefined;
  onAnswer: (answer: VocabularyQuizAnswerInput, isCorrect: boolean) => void;
}) {
  const messages = useLessonMessages();

  if (entry.type === "meaning") {
    return (
      <VocabularyQuizCheck
        question={formatMessage(messages.vocabulary.whatDoesMean, {
          word: currentItem.chineseForm,
        })}
        items={quizItems}
        currentItemId={currentItem.id}
        field="meaning"
        selectedOptionId={selectedOptionId}
        onAnswer={onAnswer}
      />
    );
  }
  if (entry.type === "chineseForm") {
    return (
      <VocabularyQuizCheck
        question={formatMessage(messages.vocabulary.whichWordMeans, {
          meaning: currentItem.meaning,
        })}
        items={quizItems}
        currentItemId={currentItem.id}
        field="chineseForm"
        selectedOptionId={selectedOptionId}
        onAnswer={onAnswer}
      />
    );
  }
  if (entry.type === "blank") {
    const example = currentExamples[entry.exampleIndex!];
    if (!example) return null;
    return (
      <VocabularyFillBlankCheck
        items={quizItems}
        currentItemId={currentItem.id}
        exampleText={example.chineseText}
        hint={messages.vocabulary.completeSentence}
        selectedOptionId={selectedOptionId}
        onAnswer={onAnswer}
      />
    );
  }
  const orderExample = currentExamples[entry.exampleIndex!];
  if (!orderExample) return null;
  return (
    <VocabularySentenceOrderCheck
      items={quizItems}
      currentItemId={currentItem.id}
      exampleText={orderExample.chineseText}
      exampleTranslation={orderExample.translation}
      answered={Boolean(selectedOptionId)}
      onAnswer={onAnswer}
    />
  );
}

function QuizOptionList({
  options,
  selectedOptionId,
  onAnswer,
}: {
  options: { id: string; label: string; isCorrect: boolean }[];
  selectedOptionId: string | undefined;
  onAnswer: (optionId: string, isCorrect: boolean) => void;
}) {
  const messages = useLessonMessages();
  const revealResult = Boolean(selectedOptionId);

  return (
    <div className="mt-2.5 flex flex-col gap-2">
      {options.map((option) => {
        const isSelected = option.id === selectedOptionId;
        // Color alone can't carry correct/incorrect (components.md: "The
        // correct state should include text or icons, not color alone") -
        // these were color-only before this fix. Check/X icons plus an
        // enriched aria-label (screen readers don't see decorative,
        // aria-hidden icons) cover both the visual and non-visual case.
        const showCorrect = revealResult && option.isCorrect;
        const showIncorrect = revealResult && isSelected && !option.isCorrect;
        return (
          <button
            key={option.id}
            type="button"
            onClick={() => onAnswer(option.id, option.isCorrect)}
            disabled={revealResult}
            aria-label={
              showCorrect
                ? formatMessage(messages.vocabulary.correctAnswer, {
                    option: option.label,
                  })
                : showIncorrect
                  ? formatMessage(messages.vocabulary.incorrectAnswer, {
                      option: option.label,
                    })
                  : undefined
            }
            className={cn(
              "flex items-center justify-between gap-2 rounded-control border border-border-strong px-3 py-2 text-left font-interface text-body transition-colors duration-fast ease-standard",
              "disabled:pointer-events-none",
              showCorrect
                ? "border-secondary-500 bg-secondary-900 text-secondary-300"
                : showIncorrect
                  ? "border-primary-500 bg-primary-900 text-primary-300"
                  : "bg-page text-text-primary",
            )}
          >
            {option.label}
            {showCorrect && (
              <Check className="size-4 shrink-0" aria-hidden="true" />
            )}
            {showIncorrect && (
              <X className="size-4 shrink-0" aria-hidden="true" />
            )}
          </button>
        );
      })}
    </div>
  );
}

function VocabularyQuizCheck({
  question,
  items,
  currentItemId,
  field,
  selectedOptionId,
  onAnswer,
}: {
  question: string;
  items: VocabularyQuizItem[];
  currentItemId: string;
  field: VocabularyQuizField;
  selectedOptionId: string | undefined;
  onAnswer: (answer: VocabularyQuizAnswerInput, isCorrect: boolean) => void;
}) {
  // Memoized so re-renders triggered by answering (a state change, not a
  // new word) don't reshuffle the options out from under the learner.
  // Seeded (not Math.random) so the server-rendered shuffle matches the
  // client's hydration pass exactly - see seededRandom's doc comment.
  const options = useMemo(
    () =>
      buildVocabularyQuizOptions(
        items,
        currentItemId,
        field,
        undefined,
        seededRandom(`${currentItemId}:${field}`),
      ),
    [items, currentItemId, field],
  );
  if (options.length < 2) return null;

  return (
    <div className="rounded-card bg-surface p-4">
      <Body className="font-semibold">{question}</Body>
      <QuizOptionList
        options={options}
        selectedOptionId={selectedOptionId}
        onAnswer={(optionId, isCorrect) =>
          onAnswer({ type: "OPTION", optionId }, isCorrect)
        }
      />
    </div>
  );
}

