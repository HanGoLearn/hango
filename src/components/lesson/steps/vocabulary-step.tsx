type ScenarioDifficulty =
  | "BEGINNER"
  | "INTERMEDIATE"
  | "UPPER_INTERMEDIATE"
  | "ADVANCED";

const DEFAULT_HAN_VOICE = "cedar";

/**
 * Redesigned 2026-08-10 (user request): one word at a time instead of a
 * full grid up front — a flashcard, its example(s), and a quick check
 * before moving to the next word. Every check is built from the lesson's
 * own vocabulary and example sentences (`vocabulary-quiz.ts`), never
 * generated by AI, so it costs nothing per learner per word. Examples are
 * hand-authored content (live AI generation removed 2026-08-14) and arrive
 * already loaded with `vocabulary` (`content/vocabulary.ts`'s
 * `getVocabularyForLesson`), same as Grammar's - no per-word fetch or
 * loading spinner (2026-08-19, project/learning-journey-optimization.md
 * Facet C). Word arrival still fires one lightweight call
 * (`recordVocabularyWordSeenAction`) to mark the word as seen for progress
 * tracking, without re-fetching its content.
 *
 * Difficulty-scaled question plan (user request, 2026-08-11): Beginner asks
 * meaning, reverse-translation, one "complete the sentence" pulled from the
 * word's hardest example, and one "put the sentence in order" — 4 total,
 * easy to hard, enough to show real learning instead of just the original 2.
 * Intermediate adds a second fill-blank from the word's easiest example — 5
 * total. Advanced adds a third fill-blank from a middle-difficulty example —
 * 6 total. Fill-blank/order questions only render once enough examples are
 * loaded, since they need real sentence text, not just the word list.
 *
 * Pinyin recognition swapped for sentence-ordering (2026-08-16, user
 * feedback): pinyin, meaning, and reverse-translation all tested the exact
 * same character<->meaning/sound association seconds apart with the answer
 * still on screen, and none of the 4 questions required the learner to
 * actually construct anything. The swap is a like-for-like count
 * replacement (still 4/5/6 total), so `vocabularyQuestionsPerWord()`
 * (points-system.ts) needed no change — see points_system.md Part 1.
 */
export function VocabularyStep({
  vocabulary,
  difficulty,
  lessonId,
  onContinue,
}: {
  vocabulary: LessonWithContent["vocabulary"];
  difficulty: ScenarioDifficulty;
  lessonId: string;
  onContinue: () => void;
}) {
  const { showPinyin, showTranslation } = useLessonDisplayPrefs();
  const [index, setIndex] = useState(0);
  const [direction, setDirection] = useState<"forward" | "back">("forward");
  const [answeredByQuestion, setAnsweredByQuestion] = useState<
    Record<string, string>
  >({});
  const seenWordIdsRef = useRef<Set<string>>(new Set());
  /**
   * Buffers the current word's quiz answers instead of sending each one
   * the instant it's tapped - flushed as one batched call whenever the
   * learner leaves the word (Next/Back/finishing the step), not per
   * question (2026-08-19, project/learning-journey-optimization.md
   * Facet C follow-up). The green/red reveal itself is unaffected - it's
   * computed client-side (vocabulary-quiz.ts) and shown from local state
   * regardless of when/whether this buffer has been sent yet.
   */
  const pendingAttemptsRef = useRef<VocabularyQuizAttemptInput[]>([]);

  const current = vocabulary[index];
  const currentItem = current?.vocabularyItem;
  const isLast = index === vocabulary.length - 1;
  const currentExamples = currentItem?.examples ?? [];

  function flushPendingAttempts() {
    if (pendingAttemptsRef.current.length === 0) return;
    const attempts = pendingAttemptsRef.current;
    pendingAttemptsRef.current = [];
    void recordVocabularyQuizAttemptsAction(lessonId, attempts);
  }

  useEffect(() => {
    if (!currentItem) return;
    if (seenWordIdsRef.current.has(currentItem.id)) return;
    seenWordIdsRef.current.add(currentItem.id);
    void recordVocabularyWordSeenAction(currentItem.id);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [currentItem?.id]);

  // Safety net for SPA-internal navigation away from this step
  // (StepNavigation, browser back within the app) - a hard tab close/
  // refresh doesn't run this, same accepted trade-off as leaving mid-word
  // (see the chat record - at most one word's worth of attempts, never the
  // whole session).
  useEffect(() => {
    return () => flushPendingAttempts();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  // Memoized: a stable reference is required so the option-shuffling
  // useMemo calls downstream (VocabularyQuizCheck/VocabularyFillBlankCheck)
  // actually skip recompute on re-render instead of seeing a "new" array
  // every time and reshuffling anyway.
  const quizItems: VocabularyQuizItem[] = useMemo(
    () =>
      vocabulary.map((v) => ({
        id: v.vocabularyItem.id,
        meaning: v.vocabularyItem.meaning,
        pinyin: v.vocabularyItem.pinyin,
        chineseForm: v.vocabularyItem.chineseForm,
      })),
    [vocabulary],
  );

  if (!currentItem) {
    return (
      <div className="flex flex-col gap-4">
        <SectionTitle>Vocabulary</SectionTitle>
        <Body>No vocabulary in this lesson.</Body>
        <Button type="button" onClick={onContinue} className="self-start">
          Continue
        </Button>
      </div>
    );
  }

  function goTo(nextIndex: number, nextDirection: "forward" | "back") {
    flushPendingAttempts();
    setDirection(nextDirection);
    setIndex(nextIndex);
  }

  function handleAnswer(
    questionKey: string,
    optionId: string,
    isCorrect: boolean,
    vocabularyItemId: string,
  ) {
    if (answeredByQuestion[questionKey]) return;
    setAnsweredByQuestion((previous) => ({
      ...previous,
      [questionKey]: optionId,
    }));
    pendingAttemptsRef.current.push({ vocabularyItemId, questionKey, isCorrect });
  }

  const cardStyle: CSSProperties = {
    animation: "card-slide-in var(--duration-slow) var(--ease-standard)",
    ["--card-slide-x" as string]: direction === "forward" ? "24px" : "-24px",
  };

  // Fill-blank example indices, easiest to hardest — examples are authored
  // in that order, so index 0 is always the simplest, the last is always
  // the hardest.
  const fillBlankIndices: number[] = [];
  if (difficulty === "BEGINNER" && currentExamples.length >= 2) {
    // Beginner gets one fill-blank, from the hardest of its 3 examples —
    // the 4th and final question in the easy-to-hard progression (user
    // request, 2026-08-11: 2 questions no longer showed real learning).
    fillBlankIndices.push(currentExamples.length - 1);
  }
  if (difficulty !== "BEGINNER" && currentExamples.length >= 2) {
    fillBlankIndices.push(0, currentExamples.length - 1);
  }
  if (difficulty === "ADVANCED" && currentExamples.length >= 3) {
    fillBlankIndices.splice(
      1,
      0,
      Math.floor((currentExamples.length - 1) / 2),
    );
  }

  // One sentence-order question per word, always shown (replaces the old
  // pinyin-recognition question) - picks an example fill-blank hasn't
  // already claimed, so the two never quiz the same sentence.
  const orderExampleIndex = pickOrderExampleIndex(
    currentExamples.length,
    fillBlankIndices,
  );

  return (
    <div className="flex flex-col gap-4">
      <SectionTitle>Vocabulary</SectionTitle>

      <div className="relative overflow-hidden rounded-panel bg-linear-to-br from-secondary-900 via-secondary-700 to-accent-700 px-5 pt-5 pb-16">
        <Body className="max-w-[70%] font-display text-[1.15rem] text-on-color-light italic">
          &ldquo;Here are the words you&rsquo;ll need for this lesson.&rdquo;
        </Body>
        <div className="mt-2">
          <HanSpeechButton
            text="Here are the words you'll need for this lesson."
            voice={DEFAULT_HAN_VOICE}
            responseLanguage="English"
          />
        </div>
        <HanMascot
          pose="curious"
          size={132}
          className="pointer-events-none absolute -right-3 -bottom-3 drop-shadow-[0_12px_18px_rgba(0,0,0,0.35)]"
        />
      </div>

      <div
        className="flex items-center justify-center gap-1.5"
        role="progressbar"
        aria-valuenow={index + 1}
        aria-valuemin={1}
        aria-valuemax={vocabulary.length}
        aria-label="Word progress"
      >
        {vocabulary.map((v, i) => (
          <span
            key={v.vocabularyItem.id}
            className={cn(
              "h-1.5 w-6 rounded-full transition-colors duration-base ease-standard",
              i < index && "bg-secondary-500",
              i === index && "bg-accent-500",
              i > index && "bg-border",
            )}
          />
        ))}
      </div>

      <div key={currentItem.id} style={cardStyle} className="flex flex-col gap-3">
        <div className="relative overflow-hidden rounded-panel bg-linear-to-br from-secondary-700 to-accent-700 px-6 py-7 text-center">
          <div className="absolute top-3 right-3">
            <AudioPlayButton
              label={`pronunciation of ${currentItem.chineseForm}`}
              size="md"
              fetchUrl={() => getVocabularyItemAudioAction(currentItem.id)}
            />
          </div>

          <ChineseText className="text-5xl text-on-color-light">
            {currentItem.chineseForm}
          </ChineseText>
          {showPinyin && (
            <Pinyin className="mt-1 font-mono text-[1.05rem] text-accent-300">
              {currentItem.pinyin}
            </Pinyin>
          )}
          <Body className="mt-1 font-semibold text-on-color-light">
            {currentItem.meaning}
          </Body>
          {currentItem.partOfSpeech && (
            <span className="mt-2 inline-block rounded-full bg-on-color-light/20 px-3 py-0.5 font-interface text-caption text-on-color-light">
              {currentItem.partOfSpeech}
            </span>
          )}
        </div>

        <div className="rounded-card bg-surface p-4">
          <Caption className="text-text-muted">Example</Caption>

          {currentExamples.length === 0 && (
            <Caption className="mt-2">No examples available.</Caption>
          )}

          {currentExamples.map((example) => (
            <div
              key={example.id}
              className="mt-2 flex gap-2 border-t border-border pt-2 first:border-t-0 first:pt-0"
            >
              <AudioPlayButton
                label={`example ${example.chineseText}`}
                fetchUrl={() => getVocabularyExampleAudioAction(example.id)}
              />
              <div className="flex flex-col gap-0.5">
                <ChineseText className="text-body">
                  {example.chineseText}
                </ChineseText>
                {showPinyin && <Pinyin>{example.pinyin}</Pinyin>}
                {showTranslation && (
                  <Translation>{example.translation}</Translation>
                )}
              </div>
            </div>
          ))}

          <AskAiButton
            label="Practice this with AI"
            contextPatch={{
              selectedDialogueLine: {
                chineseText: currentItem.chineseForm,
                pinyin: currentItem.pinyin,
                translation: currentItem.meaning,
              },
            }}
          />
        </div>

        <VocabularyQuizCheck
          question={`What does ${currentItem.chineseForm} mean?`}
          items={quizItems}
          currentItemId={currentItem.id}
          field="meaning"
          selectedOptionId={answeredByQuestion[`${currentItem.id}:meaning`]}
          onAnswer={(optionId, isCorrect) =>
            handleAnswer(
              `${currentItem.id}:meaning`,
              optionId,
              isCorrect,
              currentItem.id,
            )
          }
        />

        <VocabularyQuizCheck
          question={`Which word means "${currentItem.meaning}"?`}
          items={quizItems}
          currentItemId={currentItem.id}
          field="chineseForm"
          selectedOptionId={
            answeredByQuestion[`${currentItem.id}:chineseForm`]
          }
          onAnswer={(optionId, isCorrect) =>
            handleAnswer(
              `${currentItem.id}:chineseForm`,
              optionId,
              isCorrect,
              currentItem.id,
            )
          }
        />

        {fillBlankIndices.map((exampleIndex, position) => (
          <VocabularyFillBlankCheck
            key={`${currentItem.id}:blank:${exampleIndex}`}
            items={quizItems}
            currentItemId={currentItem.id}
            exampleText={currentExamples[exampleIndex]!.chineseText}
            hint={position === 0 ? "Complete the sentence" : undefined}
            selectedOptionId={
              answeredByQuestion[`${currentItem.id}:blank:${exampleIndex}`]
            }
            onAnswer={(optionId, isCorrect) =>
              handleAnswer(
                `${currentItem.id}:blank:${exampleIndex}`,
                optionId,
                isCorrect,
                currentItem.id,
              )
            }
          />
        ))}

        {currentExamples[orderExampleIndex] && (
          <VocabularySentenceOrderCheck
            key={`${currentItem.id}:order`}
            items={quizItems}
            currentItemId={currentItem.id}
            exampleText={currentExamples[orderExampleIndex]!.chineseText}
            exampleTranslation={currentExamples[orderExampleIndex]!.translation}
            answered={Boolean(answeredByQuestion[`${currentItem.id}:order`])}
            onAnswer={(optionId, isCorrect) =>
              handleAnswer(
                `${currentItem.id}:order`,
                optionId,
                isCorrect,
                currentItem.id,
              )
            }
          />
        )}
      </div>

      <div className="mt-2 flex items-center justify-between gap-3">
        <button
          type="button"
          onClick={() => goTo(index - 1, "back")}
          disabled={index === 0}
          className="flex items-center gap-1 font-interface text-supporting text-text-secondary transition-opacity duration-fast ease-standard hover:text-text-primary disabled:pointer-events-none disabled:opacity-0"
        >
          <ChevronLeft className="size-4" aria-hidden="true" />
          Back
        </button>

        <Caption className="text-text-muted">
          {index + 1} of {vocabulary.length}
        </Caption>

        <Button
          type="button"
          onClick={() => {
            if (isLast) {
              flushPendingAttempts();
              onContinue();
            } else {
              goTo(index + 1, "forward");
            }
          }}
        >
          {isLast ? "Continue" : "Next word"}
        </Button>
      </div>
    </div>
  );
}

function QuizOptionList({
  options,
  selectedOptionId,
  onAnswer,
}: {
  options: { id: string; label: string; isCorrect: boolean }[];
  selectedOptionId: string | undefined;
  onAnswer: (optionId: string, isCorrect: boolean) => void;
}) {
  const revealResult = Boolean(selectedOptionId);

  return (
    <div className="mt-2.5 flex flex-col gap-2">
      {options.map((option) => {
        const isSelected = option.id === selectedOptionId;
        // Color alone can't carry correct/incorrect (components.md: "The
        // correct state should include text or icons, not color alone") -
        // these were color-only before this fix. Check/X icons plus an
        // enriched aria-label (screen readers don't see decorative,
        // aria-hidden icons) cover both the visual and non-visual case.
        const showCorrect = revealResult && option.isCorrect;
        const showIncorrect = revealResult && isSelected && !option.isCorrect;
        return (
          <button
            key={option.id}
            type="button"
            onClick={() => onAnswer(option.id, option.isCorrect)}
            disabled={revealResult}
            aria-label={
              showCorrect
                ? `${option.label} (correct answer)`
                : showIncorrect
                  ? `${option.label} (your answer, incorrect)`
                  : undefined
            }
            className={cn(
              "flex items-center justify-between gap-2 rounded-control border border-border-strong px-3 py-2 text-left font-interface text-body transition-colors duration-fast ease-standard",
              "disabled:pointer-events-none",
              showCorrect
                ? "border-secondary-500 bg-secondary-900 text-secondary-300"
                : showIncorrect
                  ? "border-primary-500 bg-primary-900 text-primary-300"
                  : "bg-page text-text-primary",
            )}
          >
            {option.label}
            {showCorrect && (
              <Check className="size-4 shrink-0" aria-hidden="true" />
            )}
            {showIncorrect && (
              <X className="size-4 shrink-0" aria-hidden="true" />
            )}
          </button>
        );
      })}
    </div>
  );
}

function VocabularyQuizCheck({
  question,
  items,
  currentItemId,
  field,
  selectedOptionId,
  onAnswer,
}: {
  question: string;
  items: VocabularyQuizItem[];
  currentItemId: string;
  field: VocabularyQuizField;
  selectedOptionId: string | undefined;
  onAnswer: (optionId: string, isCorrect: boolean) => void;
}) {
  // Memoized so re-renders triggered by answering (a state change, not a
  // new word) don't reshuffle the options out from under the learner.
  // Seeded (not Math.random) so the server-rendered shuffle matches the
  // client's hydration pass exactly - see seededRandom's doc comment.
  const options = useMemo(
    () =>
      buildVocabularyQuizOptions(
        items,
        currentItemId,
        field,
        undefined,
        seededRandom(`${currentItemId}:${field}`),
      ),
    [items, currentItemId, field],
  );
  if (options.length < 2) return null;

  return (
    <div className="rounded-card bg-surface p-4">
      <Body className="font-semibold">{question}</Body>
      <QuizOptionList
        options={options}
        selectedOptionId={selectedOptionId}
        onAnswer={onAnswer}
      />
    </div>
  );
}

function VocabularyFillBlankCheck({
  items,
  currentItemId,
  exampleText,
  hint,
  selectedOptionId,
  onAnswer,
}: {
  items: VocabularyQuizItem[];
  currentItemId: string;
  exampleText: string;
  hint?: string;
  selectedOptionId: string | undefined;
  onAnswer: (optionId: string, isCorrect: boolean) => void;
}) {
  // Memoized for the same reason as VocabularyQuizCheck's options — keeps
  // option order stable across the re-render that answering triggers.
  // Seeded for the same hydration-consistency reason too.
  const question = useMemo(
    () =>
      buildFillBlankQuestion(
        items,
        currentItemId,
        exampleText,
        undefined,
        seededRandom(`${currentItemId}:blank:${exampleText}`),
      ),
    [items, currentItemId, exampleText],
  );
  if (!question) return null;

  return (
    <div className="rounded-card bg-surface p-4">
      {hint && <Caption className="text-text-muted">{hint}</Caption>}
      <ChineseText className="mt-1 text-body font-semibold">
        {question.sentenceWithBlank}
      </ChineseText>
      <QuizOptionList
        options={question.options}
        selectedOptionId={selectedOptionId}
        onAnswer={onAnswer}
      />
    </div>
  );
}

/**
 * "Put the sentence in order" check (2026-08-16, replaces the pinyin
 * question - see the module doc comment). Tap-to-order UI mirrors
 * ExerciseItem's SENTENCE_ORDERING interaction pattern
 * (components/exercise/exercise-item.tsx), but is self-contained: this app
 * has no live content using that Exercise type yet, and Vocabulary's checks
 * are built client-side from lesson data, not from Exercise/ExerciseOption
 * rows, so it doesn't share that component's server-submit flow.
 */
function VocabularySentenceOrderCheck({
  items,
  currentItemId,
  exampleText,
  exampleTranslation,
  answered,
  onAnswer,
}: {
  items: VocabularyQuizItem[];
  currentItemId: string;
  exampleText: string;
  exampleTranslation: string;
  answered: boolean;
  onAnswer: (optionId: string, isCorrect: boolean) => void;
}) {
  // Memoized for the same reason as the other checks — keeps token order
  // stable across the re-render that submitting triggers. Seeded for the
  // same hydration-consistency reason too.
  const question = useMemo(
    () =>
      buildSentenceOrderQuestion(
        items,
        currentItemId,
        exampleText,
        exampleTranslation,
        seededRandom(`${currentItemId}:order:${exampleText}`),
      ),
    [items, currentItemId, exampleText, exampleTranslation],
  );
  const [pool, setPool] = useState<string[]>(question?.shuffledTokens ?? []);
  const [built, setBuilt] = useState<string[]>([]);
  const [submittedCorrect, setSubmittedCorrect] = useState<boolean | null>(
    null,
  );

  if (!question) return null;

  // Returning to a word already answered on a prior visit (Back button):
  // this component remounts fresh (its parent card is keyed by word id), so
  // `submittedCorrect` starts null even though `answered` is true - show the
  // correct order read-only rather than an empty board.
  const correctOrder = question.correctOrder;
  const isDone = answered || submittedCorrect !== null;
  const isComplete = built.length === correctOrder.length;
  const displayTokens =
    answered && submittedCorrect === null ? correctOrder : built;

  function handleSubmit() {
    const isCorrect = built.every(
      (token, index) => token === correctOrder[index],
    );
    setSubmittedCorrect(isCorrect);
    onAnswer("submitted", isCorrect);
  }

  return (
    <div className="rounded-card bg-surface p-4">
      <Caption className="text-text-muted">Put the sentence in order</Caption>
      <Body className="mt-1 font-semibold">{question.translation}</Body>

      <div className="mt-2.5 flex min-h-11 flex-wrap gap-2 rounded-control border-2 border-dashed border-border p-2">
        {displayTokens.length === 0 && (
          <Caption>Tap the words below in the right order.</Caption>
        )}
        {displayTokens.map((token, index) => (
          <button
            key={`${token}-${index}`}
            type="button"
            disabled={isDone}
            onClick={() => {
              setBuilt(built.filter((_, i) => i !== index));
              setPool([...pool, token]);
            }}
            className={cn(
              "rounded-full border-2 px-3 py-1 font-chinese text-body",
              submittedCorrect === true &&
                "border-secondary-500 bg-secondary-900 text-secondary-300",
              submittedCorrect === false &&
                "border-primary-500 bg-primary-900 text-primary-300",
              submittedCorrect === null &&
                "border-primary-500 bg-primary-500/15",
            )}
          >
            {token}
          </button>
        ))}
      </div>

      {submittedCorrect !== null && (
        // Solid fill + on-color-light, not a fixed palette-step text color
        // directly on bg-surface - surface inverts between themes and no
        // single fixed shade (tried -300 through -700) clears WCAG AA
        // against both its dark and light values at once (same issue
        // BottomNav's active-tab color hit earlier this pass).
        <span
          className={cn(
            "mt-2 inline-flex items-center gap-1.5 rounded-full px-2.5 py-1 font-interface text-caption font-semibold text-on-color-light",
            submittedCorrect ? "bg-secondary-500" : "bg-primary-500",
          )}
          role="status"
        >
          {submittedCorrect ? (
            <Check className="size-3.5 shrink-0" aria-hidden="true" />
          ) : (
            <X className="size-3.5 shrink-0" aria-hidden="true" />
          )}
          {submittedCorrect ? "Correct!" : "Not quite"}
        </span>
      )}

      {!isDone && (
        <div className="mt-2 flex flex-wrap gap-2">
          {pool.map((token, index) => (
            <button
              key={`${token}-${index}`}
              type="button"
              onClick={() => {
                setPool(pool.filter((_, i) => i !== index));
                setBuilt([...built, token]);
              }}
              className="rounded-full border-2 border-border px-3 py-1 font-chinese text-body"
            >
              {token}
            </button>
          ))}
        </div>
      )}

      {!isDone && (
        <Button
          type="button"
          variant="secondary"
          className="mt-3"
          disabled={!isComplete}
          onClick={handleSubmit}
        >
          Check
        </Button>
      )}

      {submittedCorrect === false && (
        <Caption className="mt-2 text-error-500">
          Correct order: {question.correctOrder.join(" ")}
        </Caption>
      )}
    </div>
  );
}
